"""Build paper-ready B4/B5 figures from completed D_dev summaries and selection artifacts.

Expected tree: reports/task7/{B4,B5}/seed_13/... generated by run_b4_b5.py.
Missing runs are reported and omitted; no metric is imputed.
"""
import argparse, csv, json
from pathlib import Path
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np


def read_json(path):
    return json.loads(path.read_text(encoding='utf-8'))


def main():
    p=argparse.ArgumentParser()
    p.add_argument('--reports-dir',type=Path,default=Path('reports/task7'))
    p.add_argument('--out-dir',type=Path,default=Path('reports/task7/figures'))
    p.add_argument('--seeds',type=int,nargs='+',default=[13,42,2026])
    p.add_argument('--methods',nargs='+',choices=['B4','B5'],default=['B4','B5'])
    a=p.parse_args()
    rows=[]; selection_rows=[]
    for method in a.methods:
        for seed in a.seeds:
            base=a.reports_dir/method/f'seed_{seed:02d}'
            for t in (1,2,3):
                cp=f'student_ckpt_{t:03d}'
                sp=base/f'eval_{cp}_dev.summary.json'
                if sp.exists():
                    s=read_json(sp)
                    rows.append({'method':method,'seed':seed,'round':t,'checkpoint':cp,
                                 'accuracy':s['accuracy'],'lenient_accuracy':s['lenient_accuracy'],
                                 'format_compliance':s['format_compliance'],'mean_output_tokens':s['mean_output_tokens'],
                                 'n_problems':s['n_problems']})
                else: print(f'[WARN] missing eval summary: {sp}')
            log=base/'selection_log.jsonl'
            if log.exists():
                with log.open(encoding='utf-8') as f:
                    for line in f:
                        if line.strip():
                            r=json.loads(line)
                            if r.get('record_type')=='selection' and r.get('method')==method:
                                selection_rows.append(r)
            else: print(f'[WARN] missing selection log: {log}')
    if not rows: raise RuntimeError('no evaluation summaries found; run B4/B5 rounds first')
    a.out_dir.mkdir(parents=True,exist_ok=True)
    metrics=['accuracy','lenient_accuracy','format_compliance']
    # Round-wise mean and sample standard deviation across seeds.
    grouped={}
    for m in a.methods:
        for metric in metrics:
            means=[]; stds=[]; rounds=[]
            for t in (1,2,3):
                vals=[r[metric] for r in rows if r['method']==m and r['round']==t]
                if vals:
                    rounds.append(t); means.append(float(np.mean(vals))); stds.append(float(np.std(vals,ddof=1)) if len(vals)>1 else 0.0)
            if rounds: grouped[(m,metric)]=(rounds,means,stds)
    fig,ax=plt.subplots(figsize=(8.5,5.2))
    for m in a.methods:
        if (m,'accuracy') in grouped:
            x,y,e=grouped[(m,'accuracy')]; ax.errorbar(x,y,yerr=e,marker='o',capsize=4,label=m)
    ax.set(xticks=[1,2,3],xlabel='Student checkpoint',ylabel='D_dev exact-match accuracy',ylim=(0,1.02),title='B4 vs B5: strict accuracy across rounds')
    ax.grid(True,alpha=.25); ax.legend(); fig.tight_layout(); fig.savefig(a.out_dir/'fig_b4_b5_dev_accuracy.png',dpi=300); plt.close(fig)

    fig,axes=plt.subplots(1,2,figsize=(11,4.6),sharey=True)
    for ax,metric,title in zip(axes,['lenient_accuracy','format_compliance'],['Lenient answer accuracy','Output format compliance']):
        for m in a.methods:
            if (m,metric) in grouped:
                x,y,e=grouped[(m,metric)]; ax.errorbar(x,y,yerr=e,marker='o',capsize=4,label=m)
        ax.set(xticks=[1,2,3],xlabel='Student checkpoint',title=title,ylim=(0,1.02)); ax.grid(True,alpha=.25); ax.legend()
    axes[0].set_ylabel('D_dev score'); fig.tight_layout(); fig.savefig(a.out_dir/'fig_b4_b5_secondary_metrics.png',dpi=300); plt.close(fig)

    # Budget utilization based on selected IDs and recorded Budget-A token counts.
    budgets=[]
    for m in a.methods:
        for seed in a.seeds:
            base=a.reports_dir/m/f'seed_{seed:02d}'
            for t in range(3):
                tp=base/f'round_{t:03d}'/'train_set.json'
                if tp.exists():
                    x=read_json(tp); budgets.append({'method':m,'seed':seed,'round':t,'tokens':x['trajectory_tokens'],'budget':x['trajectory_token_budget'],'utilization':x['trajectory_tokens']/x['trajectory_token_budget']})
    if budgets:
        fig,ax=plt.subplots(figsize=(8.5,5.2))
        for m in a.methods:
            means=[]; stds=[]; xs=[]
            for t in range(3):
                vals=[r['utilization'] for r in budgets if r['method']==m and r['round']==t]
                if vals: xs.append(t); means.append(float(np.mean(vals))); stds.append(float(np.std(vals,ddof=1)) if len(vals)>1 else 0)
            if xs: ax.errorbar(xs,means,yerr=stds,marker='o',capsize=4,label=m)
        ax.set(xticks=[0,1,2],xlabel='Training round',ylabel='Budget A utilization',ylim=(0,1.05),title='Token-budget utilization by selection method')
        ax.grid(True,alpha=.25); ax.legend(); fig.tight_layout(); fig.savefig(a.out_dir/'fig_b4_b5_budget_utilization.png',dpi=300); plt.close(fig)

    if selection_rows:
        fig,ax=plt.subplots(figsize=(8.5,5.2))
        for m in a.methods:
            xs=[]; ys=[]
            for t in range(3):
                vals=[float(r['l_proxy']) for r in selection_rows if r.get('method')==m and int(r.get('round',-1))==t and r.get('selected') and r.get('l_proxy') is not None]
                if vals: xs.append(t); ys.append(float(np.mean(vals)))
            if xs: ax.plot(xs,ys,marker='o',label=m)
        ax.set(xticks=[0,1,2],xlabel='Training round',ylabel='Mean selected L_proxy',title='Learnability of selected trajectories')
        ax.grid(True,alpha=.25); ax.legend(); fig.tight_layout(); fig.savefig(a.out_dir/'fig_b4_b5_selected_learnability.png',dpi=300); plt.close(fig)

    csv_path=a.out_dir/'b4_b5_dev_metrics.csv'
    with csv_path.open('w',newline='',encoding='utf-8-sig') as f:
        w=csv.DictWriter(f,fieldnames=list(rows[0])); w.writeheader(); w.writerows(rows)
    budget_path=a.out_dir/'b4_b5_budget_utilization.csv'
    if budgets:
        with budget_path.open('w',newline='',encoding='utf-8-sig') as f:
            w=csv.DictWriter(f,fieldnames=list(budgets[0])); w.writeheader(); w.writerows(budgets)
    print(f'[PASS] figures and CSV written to {a.out_dir}')
    for x in sorted(a.out_dir.glob('fig_*.png')): print(f'[FIGURE] {x}')

if __name__=='__main__': main()
